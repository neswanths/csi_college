function createToken() {
  const officePrefix = (selectedOffice()?.title || "Office")
    .split(" ")
    .map((word) => word[0])
    .join("")
    .slice(0, 2)
    .toUpperCase();
  const number = Math.floor(1000 + Math.random() * 9000);
  return `${officePrefix}-${number}`;
}

function confirmSlot(slot) {
  if (state.submitted) {
    setState({ error: t("duplicatePrevented") });
    return;
  }

  if (!slotAvailable(slot)) {
    setState({ error: t("slotFilled"), slot: "" });
    return;
  }

  bookingCounts.set(slotKey(slot), bookingCount(slot) + 1);
  setState({
    screen: "confirmation",
    slot,
    token: createToken(),
    submitted: true,
    error: "",
  });
}

function goBack() {
  const order = ["language", "office", "service", "date", "period", "time", "confirmation"];
  const index = order.indexOf(state.screen);
  const previous = order[Math.max(index - 1, 0)];
  setState({ screen: previous, error: "" });
}

function resetFlow() {
  setState({
    screen: "language",
    language: "en",
    officeId: "",
    serviceId: "",
    dateMode: "",
    appointmentDate: "",
    periodId: "",
    slot: "",
    token: "",
    audioStatus: "",
    error: "",
    submitted: false,
  });
}

function currentChoicesForSpeech() {
  if (state.screen === "language") {
    return languages.map((language) => language.title);
  }

  if (state.screen === "office") {
    return offices.map(displayOffice);
  }

  if (state.screen === "service") {
    return availableServices().map(displayService);
  }

  if (state.screen === "date") {
    const baseDate = todayDate();
    const validChoices = [
      { title: t("today"), value: toDateInputValue(baseDate) },
      { title: t("tomorrow"), value: toDateInputValue(addDays(baseDate, 1)) },
    ]
      .filter((choice) => isWorkingDay(choice.value))
      .map((choice) => `${choice.title}, ${speechDate(choice.value)}`);
    return [...validChoices, t("chooseAnotherDate")];
  }

  if (state.screen === "period") {
    return availablePeriods().map((period) => `${displayPeriod(period)}, ${speechTimeRange(period)}`);
  }

  if (state.screen === "time") {
    return slotsForPeriod(state.periodId).map(speechTime);
  }

  return [];
}

function currentHeading() {
  const headingByScreen = {
    language: t("languageTitle"),
    office: t("officeTitle"),
    service: t("serviceTitle"),
    date: t("dateTitle"),
    period: t("periodTitle"),
    time: t("timeTitle"),
    confirmation: t("confirmationTitle"),
  };
  return headingByScreen[state.screen];
}

function speechText() {
  if (state.screen === "language") {
    return t("languageSpeech");
  }

  if (state.screen === "confirmation") {
    return [
      t("confirmationTitle"),
      `${t("token")}: ${speechToken(state.token)}.`,
      `${t("office")}: ${displayOffice(selectedOffice())}.`,
      `${t("service")}: ${displayService(selectedService())}.`,
      `${t("date")}: ${speechDate(state.appointmentDate)}.`,
      `${t("time")}: ${speechTime(state.slot)}.`,
      t("arrival"),
    ].join(" ");
  }

  const choices = currentChoicesForSpeech()
    .map((choice, index) => `${speechNumber(index)}. ${choice}.`)
    .join(" ");
  return `${currentHeading()}. ${choices}`;
}

async function speakCurrentScreen() {
  const result = await speechUtility.speak({
    text: speechText(),
    languageId: state.language,
  });

  if (!result.ok && result.reason === "missing-telugu-voice") {
    setState({ audioStatus: t("teluguVoiceNotice") });
    return;
  }

  if (!result.ok) {
    setState({ audioStatus: t("audioUnavailable") });
    return;
  }

  if (state.audioStatus) {
    setState({ audioStatus: "" });
  }
}

function chooseDate(mode, value) {
  if (mode === "custom") {
    setState({
      dateMode: "custom",
      appointmentDate: "",
      periodId: "",
      slot: "",
      error: "",
    });
    return;
  }

  if (isPastDate(value) || !isWorkingDay(value)) {
    setState({ error: t("dateUnavailable") });
    return;
  }

  setState({
    screen: "period",
    dateMode: mode,
    appointmentDate: value,
    periodId: "",
    slot: "",
    error: "",
  });
}

function render() {
  if (state.screen === "language") {
    renderLanguage();
  } else if (state.screen === "office") {
    renderOffice();
  } else if (state.screen === "service") {
    renderService();
  } else if (state.screen === "date") {
    renderDate();
  } else if (state.screen === "period") {
    renderPeriod();
  } else if (state.screen === "time") {
    renderTime();
  } else if (state.screen === "confirmation") {
    renderConfirmation();
  }
}

app.addEventListener("click", (event) => {
  const target = event.target.closest("button");
  if (!target) {
    return;
  }

  if (target.dataset.action === "speak") {
    speakCurrentScreen();
    return;
  }

  if (target.dataset.action === "back") {
    goBack();
    return;
  }

  if (target.dataset.action === "reset") {
    resetFlow();
    return;
  }

  if (target.dataset.language) {
    setState({
      language: target.dataset.language,
      screen: "office",
      officeId: "",
      serviceId: "",
      appointmentDate: "",
      periodId: "",
      slot: "",
      error: "",
    });
    return;
  }

  if (target.dataset.office) {
    setState({
      screen: "service",
      officeId: target.dataset.office,
      serviceId: "",
      appointmentDate: "",
      periodId: "",
      slot: "",
      error: "",
      submitted: false,
    });
    return;
  }

  if (target.dataset.service) {
    setState({
      screen: "date",
      serviceId: target.dataset.service,
      appointmentDate: "",
      periodId: "",
      slot: "",
      error: "",
      submitted: false,
    });
    return;
  }

  if (target.dataset.dateMode) {
    chooseDate(target.dataset.dateMode, target.dataset.date);
    return;
  }

  if (target.dataset.period) {
    setState({
      screen: "time",
      periodId: target.dataset.period,
      slot: "",
      error: "",
    });
    return;
  }

  if (target.dataset.slot) {
    confirmSlot(target.dataset.slot);
  }
});

app.addEventListener("change", (event) => {
  if (event.target.id !== "customDate") {
    return;
  }

  const value = event.target.value;
  if (!value || isPastDate(value) || !isWorkingDay(value)) {
    setState({ appointmentDate: value, periodId: "", slot: "", error: t("dateUnavailable") });
    return;
  }

  setState({
    screen: "period",
    dateMode: "custom",
    appointmentDate: value,
    periodId: "",
    slot: "",
    error: "",
  });
});

render();
