const speechUtility = {
  voices: [],
  voicesLoaded: false,
  voicesPromise: null,

  supported() {
    return "speechSynthesis" in window && "SpeechSynthesisUtterance" in window;
  },

  inspectVoices() {
    if (!this.supported()) {
      this.voices = [];
      return [];
    }

    this.voices = window.speechSynthesis.getVoices();
    this.voicesLoaded = this.voices.length > 0;
    return this.voices;
  },

  waitForVoices() {
    if (!this.supported()) {
      return Promise.resolve([]);
    }

    const existing = this.inspectVoices();
    if (existing.length > 0) {
      return Promise.resolve(existing);
    }

    if (this.voicesPromise) {
      return this.voicesPromise;
    }

    this.voicesPromise = new Promise((resolve) => {
      let settled = false;
      const finish = () => {
        if (settled) {
          return;
        }
        settled = true;
        resolve(this.inspectVoices());
      };

      if (
        "onvoiceschanged" in window.speechSynthesis &&
        typeof window.speechSynthesis.addEventListener === "function"
      ) {
        window.speechSynthesis.addEventListener("voiceschanged", finish, { once: true });
      }

      window.setTimeout(finish, 900);
    });

    return this.voicesPromise;
  },

  findVoice(languageId) {
    const requested = languageId === "te" ? "te-IN" : "en-IN";
    const base = requested.split("-")[0].toLowerCase();
    const voices = this.inspectVoices();

    return (
      voices.find((voice) => voice.lang.toLowerCase() === requested.toLowerCase()) ||
      voices.find((voice) => voice.lang.toLowerCase().startsWith(`${base}-`)) ||
      voices.find((voice) => voice.lang.toLowerCase() === base)
    );
  },

  async speak({ text, languageId }) {
    if (!this.supported()) {
      return { ok: false, reason: "unsupported" };
    }

    window.speechSynthesis.cancel();
    await this.waitForVoices();

    const utterance = new SpeechSynthesisUtterance(text);
    utterance.rate = 0.9;
    utterance.pitch = 1;
    utterance.lang = languageId === "te" ? "te-IN" : "en-IN";

    const voice = this.findVoice(languageId);
    if (languageId === "te" && !voice) {
      return { ok: false, reason: "missing-telugu-voice", voices: this.voices };
    }

    if (voice) {
      utterance.voice = voice;
      utterance.lang = voice.lang;
    }

    utterance.onerror = () => {
      if (state.screen) {
        setState({ audioStatus: t("audioUnavailable") });
      }
    };

    window.speechSynthesis.speak(utterance);
    return { ok: true, voice, voices: this.voices };
  },
};

if (
  speechUtility.supported() &&
  "onvoiceschanged" in window.speechSynthesis &&
  typeof window.speechSynthesis.addEventListener === "function"
) {
  window.speechSynthesis.addEventListener("voiceschanged", () => {
    speechUtility.inspectVoices();
  });
}

