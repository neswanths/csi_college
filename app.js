function renderDate() {
  const today = todayDate();
  const dates = [
    { mode: "today", title: t("today"), value: toDateInputValue(today) },
    { mode: "tomorrow", title: t("tomorrow"), value: toDateInputValue(addDays(today, 1)) },
  ];

  const cards = numberedCards([
    ...dates.map((item) => ({
      title: item.title,
      description: formatDate(item.value),
      data: `data-date-mode="${item.mode}" data-date="${item.value}"`,
      disabled: !isWorkingDay(item.value),
      selected: state.appointmentDate === item.value,
    })),
    {
      title: t("chooseAnotherDate"),
      description: state.dateMode === "custom" ? formatDate(state.appointmentDate) : "",
      data: 'data-date-mode="custom"',
      selected: state.dateMode === "custom",
    },
  ]);

  const dateInput = `
    <div class="date-panel ${state.dateMode === "custom" ? "" : "is-hidden"}">
      <label for="customDate">${t("selectDate")}</label>
      <input id="customDate" type="date" min="${toDateInputValue(today)}" value="${state.dateMode === "custom" ? state.appointmentDate : ""}" />
    </div>
  `;

  renderShell("date", t("dateTitle"), t("dateLead"), `${cards}${dateInput}`, {
    withSummary: true,
  });
}

